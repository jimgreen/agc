async (page) => {
  if (!page.url().includes('127.0.0.1:18766')) throw new Error('Fixture URL required');
  await page.reload();
  await page.setViewportSize({width:1366,height:768});
  const results=[];
  const check=(name,pass)=>{results.push({name,pass});if(!pass)throw new Error(name);};
  const detail=async()=>await (await page.request.get('http://127.0.0.1:18766/api/device-detail?kind=wind&id=1')).json();
  await page.getByRole('button',{name:'◉ 实时监视',exact:true}).click();
  await page.getByRole('button',{name:'设备详情',exact:true}).click();
  await page.getByRole('combobox',{name:'查看设备',exact:true}).selectOption('wind:1');
  await page.getByRole('button',{name:'控制参数',exact:true}).click();
  await page.getByRole('button',{name:'编辑 96 点曲线',exact:true}).click();
  await page.getByRole('spinbutton',{name:'本组起点 MW',exact:true}).fill('1');
  await page.getByRole('spinbutton',{name:'本组终点 MW',exact:true}).fill('3');
  await page.getByRole('button',{name:'生成本组线性曲线',exact:true}).click();
  check('ramp endpoints',await page.getByRole('spinbutton',{name:'00:00',exact:true}).inputValue()==='1' && await page.getByRole('spinbutton',{name:'05:45',exact:true}).inputValue()==='3');
  await page.getByRole('button',{name:'下一组',exact:true}).click();
  await page.getByRole('button',{name:'上一组',exact:true}).click();
  check('page preserves draft',await page.getByRole('spinbutton',{name:'05:45',exact:true}).inputValue()==='3');
  await page.getByRole('button',{name:'保存默认曲线',exact:true}).click();
  await page.locator('#curveModal').waitFor({state:'hidden'});
  const curve=(await detail()).device.presetCurve;
  check('96 point persistence',curve.length===96 && curve[0]===1 && curve[23]===3);
  const input=page.getByRole('spinbutton',{name:'控制步长 / MW',exact:true});
  await input.fill('1.7');
  await page.waitForTimeout(4500);
  check('refresh preserves unsaved edit',await input.inputValue()==='1.7');
  await page.getByRole('button',{name:'保存设备参数',exact:true}).click();
  await page.waitForTimeout(400);
  const saved=(await detail()).device;
  check('parameter saved without flattening curve',saved.controlStep===1.7 && JSON.stringify(saved.presetCurve)===JSON.stringify(curve));
  await input.fill('2.1');
  await page.getByRole('button',{name:'撤销修改',exact:true}).click();
  check('undo reloads saved value',await input.inputValue()==='1.7');
  await page.getByRole('button',{name:'编辑 96 点曲线',exact:true}).click();
  await page.getByRole('button',{name:'当前值填充全天',exact:true}).click();
  await page.getByRole('button',{name:'下一组',exact:true}).click();
  check('fill affects next group',await page.getByRole('spinbutton',{name:'06:00',exact:true}).inputValue()===String(saved.presetPower));
  await page.getByRole('button',{name:'恢复已保存曲线',exact:true}).click();
  await page.getByRole('button',{name:'上一组',exact:true}).click();
  check('restore full saved curve',await page.getByRole('spinbutton',{name:'05:45',exact:true}).inputValue()==='3');
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'控制时刻指令',exact:true}).click();
  const first=await page.locator('#deviceCommandTable tr').first().textContent();
  await page.locator('#detailCommandPager button').last().click();
  check('command pagination advances',await page.locator('#deviceCommandTable tr').first().textContent()!==first);
  await page.getByRole('button',{name:'设备列表',exact:true}).click();
  await page.getByRole('searchbox',{name:'搜索设备名或 ID',exact:true}).fill('风机01');
  check('device search',await page.locator('#deviceTable tr').count()===1);
  await page.getByRole('checkbox',{name:'全选当前页',exact:true}).check();
  await page.locator('#bulkState').selectOption('local');
  await page.getByRole('button',{name:'应用批量受控状态',exact:true}).click();
  await page.waitForTimeout(400);
  check('bulk state persists',(await detail()).device.controlState==='local');
  const initial=await (await page.request.get('http://127.0.0.1:18766/api/state?lite=1&history_since=-1')).json();
  check('initial lightweight history',initial.history.length===150 && !initial.devices[0].presetCurve);
  const unchanged=await (await page.request.get('http://127.0.0.1:18766/api/state?lite=1&history_since=150')).json();
  check('unchanged lightweight history omitted',!Object.hasOwn(unchanged,'history'));
  await page.getByRole('button',{name:'⌂ 主页面',exact:true}).click();
  await page.getByRole('button',{name:'功率趋势与资源',exact:true}).click();
  const height=await page.locator('#overviewChart').evaluate(e=>e.height);
  await page.waitForTimeout(4500);
  check('canvas height remains stable',await page.locator('#overviewChart').evaluate(e=>e.height)===height);
  await page.screenshot({path:'output/playwright/overview-trend.png'});
  return results;
}
